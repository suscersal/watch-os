// emu_slow.h - замедление эмулятора до скорости платы. ESP32-S3 (240 МГц, интерфейс рисуется программно) тратит на
// кадр время, пропорциональное числу перерисованных пикселей: полный экран 410x502 примерно 0,1 с, то есть около
// 10 кадров/с, а маленькие обновления (время, иконка) почти бесплатны. Эмулятор считает так же и после каждого
// сброса области на экран "досыпает" это время. Модель не зависит от скорости вашего ПК. Анимации идут по времени,
// поэтому кадры пропускаются, как на часах: что в эмуляторе дёргается, на плате будет дёргаться.
//   WATCH_EMU_SLOW=K          множитель (по умолчанию 1 = плата, 2 = вдвое медленнее, 0 = без замедления). Ждёт только недостающее
//                             время (то, что устройство уже потратило на отрисовку, вычитается), поэтому лаги телефона не удваиваются
//   WATCH_EMU_US_PER_PX=X     мкс на пиксель (по умолчанию EMU_US_PER_PX); подберите по замеру на самой плате
#pragma once
#include "lvgl/lvgl.h"

#define EMU_US_PER_PX    0.45     // оценка, не замер. Замерьте на плате (esp32/README.md, "Калибровка эмулятора") и задайте WATCH_EMU_US_PER_PX
#define EMU_US_PER_FLUSH 300.0    // накладные расходы на один сброс области, мкс

