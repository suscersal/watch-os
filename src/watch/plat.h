// plat.h - платформенные мелочи (источник случайных чисел). Для ESP32 будет esp_fill_random().
#pragma once
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

bool plat_random(void *buf, size_t n);   // криптостойкие случайные байты

// Локальный IPv4-адрес в Wi-Fi/LAN для показа на экране синхронизации ("192.168.0.5"). false, если сети нет.
bool plat_local_ip(char *buf, size_t n);

// Аппаратные часы (RTC). ESP32: PCF85063 на плате Waveshare; ПК: системное время (запись игнорируется).
// read - UTC epoch; false, если часы не заведены (например, у RTC сброшен флаг остановки генератора).
bool plat_rtc_read(int64_t *epoch_utc);
void plat_rtc_write(int64_t epoch_utc);

// Заряд батареи, 0..100. false, если батареи нет или её не удалось прочитать (значок в строке состояния скрывается).
// ПК: переменная окружения WATCH_BATTERY="73" или "73+" (с зарядкой) для проверки интерфейса.
bool plat_battery(int *pct, bool *charging);

// microSD. Карта вставлена и смонтирована? ESP32: монтируется и проверяется фоновой задачей раз в несколько секунд,
// вставка и извлечение на ходу подхватываются сами; карту не форматируем, нечитаемая карта считается отсутствующей.
// ПК: переменная окружения WATCH_SD=off - карты нет (по умолчанию \"вставлена\", чтобы проверять интерфейс).
bool plat_sd_present(void);
// Корень смонтированной карты (\"/sdcard\") или NULL, если карты нет. Музыка и фото кладутся в <корень>/music и <корень>/photos.
// ПК: \"data/sd\" (WATCH_SD=off - карты нет, WATCH_SD=<путь> - свой каталог).
const char *plat_sd_root(void);

// Вибромотор. Узор - чередование времени включения и паузы в мс, начиная с включения: {200,130,200} - два импульса.
// Новый узор прерывает прежний. Длина импульса ограничена 250 мс, шагов не больше 16, в конце мотор всегда выключен.
// ESP32: мотор на GPIO18 (включение выходом без ШИМ, как в заводском примере Waveshare), выключает таймер esp_timer.
// ПК: мотора нет, узор печатается в консоль строкой "[haptic] ...".
void plat_haptic(const uint16_t *pattern_ms, int n);
